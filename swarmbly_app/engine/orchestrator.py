    def _resolve(self, task_id, replicas, contract, embedder, *, policy: str = "units",
                 lang: str | None = None, budget: int | None = None,
                 items: dict[int, str] | None = None) -> dict[str, Any]:
        """One text per task: the only replica, or a consensus over replicas (§14b).

        ``policy="units"`` (independent items of a batch) returns upstream's
        per-unit consensus text. ``policy="whole"`` (a composition, a whole
        request) selects ONE complete replica: upstream per-unit consensus
        picks a medoid per unit, which on two different essays produced a
        patchwork of both, in two languages (diagnosis 2026-10-15, finding 5).
        The per-unit alignment is still computed and reported as divergence.

        ``policy="items"`` (an enumerated batch) votes per numbered item: each
        replica's answer to item *n* is parsed, the majority value wins, ties
        go to the best-ranked replica (as in ``"whole"``). Per-unit alignment
        on short answer sheets appended a second replica's re-listed items to
        the first (live smoke test 2026-10-16). When fewer than half the items
        can be parsed, the policy falls back to ``"whole"``.
        """
        meta = [{"node": r.node_id[:12], "family": r.family, "model": r.model,
                 "elapsed_ms": r.elapsed_ms, "telemetry": r.telemetry,
                 "truncated": _is_truncated(r, budget)}
                for r in replicas]
        if len(replicas) < 2:
            return {"text": replicas[0].text, "consensus": None, "replica_meta": meta,
                    "truncated": meta[0]["truncated"]}
        from swarmbly_v0.consensus import Replica as UpReplica, consensus
        result = consensus([UpReplica(replica_id=f"r{i}", text=r.text, family=r.family,
                                      model=r.model) for i, r in enumerate(replicas)],
                           contract, embedder)
        block = {
            "k": result.k, "families": list(result.families),
            "mean_agreement": round(float(result.mean_agreement), 4),
            "units": [{"label": u.label, "agreement": round(float(u.agreement), 4),
                       "text": u.text[:160]} for u in result.units],
            "low_confidence_regions": [
                {"start": r.start, "end": r.end,
                 "mean_agreement": round(float(r.mean_agreement), 4),
                 "text": r.text[:200]} for r in result.low_confidence_regions],
            "alpha_high": result.alpha_high, "alpha_low": result.alpha_low,
        }
        if policy == "units":
            return {"text": result.text or replicas[0].text, "consensus": block,
                    "replica_meta": meta,
                    "truncated": all(m["truncated"] for m in meta)}
        chosen, selection = _select_whole(replicas, meta, embedder, lang)
        if policy == "items" and items:
            vote = _vote_items(replicas, items, selection["ranking"])
            if vote is not None:
                text, report = vote
                block["selection"] = report
                return {"text": text, "consensus": block, "replica_meta": meta,
                        "truncated": False}
        block["selection"] = selection
        return {"text": replicas[chosen].text, "consensus": block, "replica_meta": meta,
                "truncated": meta[chosen]["truncated"]}

    def _assemble(self, plan, contract, resolved, bridge_backend, embedder, path):
        """Select-then-splice (SPEC §14). For an enumerated batch the items
        are independent by construction: junctions are spliced, never bridged
        (a transition sentence between list items only adds noise); seam
        similarities are still measured and reported."""
        from swarmbly_v0.assembler import fragments_from_mapping, select_then_splice
        mapping = {t.task_id: [resolved[t.task_id]["text"]] for t in plan.tasks
                   if t.task_id in resolved}
        fragments = fragments_from_mapping(mapping, plan=plan)
        if path == "enumerated":
            tau, join, policy = -2.0, True, "list: independent items, spliced (no bridges)"
        else:
            tau, join, policy = self._tau_sem(), False, "τ_sem: bridge below threshold"
        assembly = select_then_splice(fragments, contract, bridge_backend, tau,
                                      plan=plan, embedder=embedder,
                                      paragraph_join=join)
        seams = [{"left": s.left_task, "right": s.right_task,
                  "similarity": round(float(s.similarity), 4),
                  "path": "bridge" if s.bridged else "splice"}
                 for s in assembly.seams]
        return assembly.text, seams, policy

    @staticmethod
    def _assemble_composition(plan, outline, resolved, embedder):
        """Sections in outline order under the title; seams measured, never bridged."""
        import numpy as np
        texts = [composer.clean_section(resolved[t.task_id]["text"], outline.sections[i],
                                        outline.title)
                 for i, t in enumerate(plan.tasks) if t.task_id in resolved]
        seams = []
        if len(texts) >= 2:
            tails = [" ".join(t.split()[-60:]) for t in texts]
            heads = [" ".join(t.split()[:60]) for t in texts]
            vecs = np.asarray(embedder.embed(tails[:-1] + heads[1:]), dtype=float)
            norms = np.linalg.norm(vecs, axis=1, keepdims=True)
            unit = vecs / np.where(norms == 0, 1.0, norms)
            k = len(texts) - 1
            for i in range(k):
                seams.append({"left": plan.tasks[i].task_id, "right": plan.tasks[i + 1].task_id,
                              "similarity": round(float(unit[i] @ unit[k + i]), 4),
                              "path": "splice"})
        return (composer.assemble(outline, texts), seams,
                "composition: ordered sections; transitions written by the workers "
                "(no bridges)")

